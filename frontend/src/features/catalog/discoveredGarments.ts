export function getDiscoveredGarmentById(
  id: string,
): Product | undefined {
  return DISCOVERED_GARMENTS.find((item) => item.id === id);
}

export function filterDiscoveredGarments(options: {
  query?: string;
  brand?: string;
  category?: string;
  audience?: string;
  color?: string;
  occasion?: string;
  sort?: string;
}): Product[] {
  let list = [...DISCOVERED_GARMENTS];
  if (options.brand) {
    const b = options.brand.toLowerCase();
    list = list.filter(
      (item) =>
        item.brand_name.toLowerCase() === b ||
        (b === "h-m" && item.brand_name.toLowerCase() === "h&m") ||
        (b === "h&m" && item.brand_name.toLowerCase() === "h&m"),
    );
  }
  if (options.query) {
    const q = options.query.toLowerCase().trim();
    list = list.filter(
      (item) =>
        item.name.toLowerCase().includes(q) ||
        item.description.toLowerCase().includes(q) ||
        item.brand_name.toLowerCase().includes(q) ||
        item.category.toLowerCase().includes(q),
    );
  }
  if (options.category) {
    list = list.filter((item) => item.category === options.category);
  }
  if (options.audience) {
    list = list.filter(
      (item) =>
        item.audience === options.audience || item.audience === "unisex",
    );
  }
  if (options.color) {
    list = list.filter((item) =>
      item.colors.some(
        (c) => c.toLowerCase() === options.color?.toLowerCase(),
      ),
    );
  }
  if (options.occasion) {
    list = list.filter((item) =>
      item.occasions?.some(
        (o: string) => o.toLowerCase() === options.occasion?.toLowerCase(),
      ),
    );
  }
  if (options.sort === "name") {
    list.sort((a, b) => a.name.localeCompare(b.name));
  }
  return list;
}
